/**
 * Offline style evaluation: how much does each playstyle change behaviour,
 * and what does it cost in human-likeness?
 *
 * For every evaluation position, run Maia-3 once, then compute — exactly, no
 * sampling — the expected move features under each style's distribution,
 * the KL divergence from plain Maia, and how often the style's most likely
 * move equals Maia's most likely move.
 *
 * Usage: npm run eval:styles   (writes eval/style-eval.json and docs/style-eval.md)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { DirectMaiaBackend } from "../src/opponents/maia-direct-backend";
import { FEATURE_KEYS, FEATURE_LABELS, STYLES, applyStyle, expectedFeatures, positionFeatures, type Features, type StyleId } from "../src/opponents/style";

const bin = readFileSync(new URL("../public/models/maia3-5m.safetensors", import.meta.url));
const backend = new DirectMaiaBackend(bin.buffer.slice(bin.byteOffset, bin.byteOffset + bin.byteLength) as ArrayBuffer);
const { positions } = JSON.parse(readFileSync(new URL("../eval/positions.json", import.meta.url), "utf8"));
const limit = Number(process.argv[2] ?? positions.length);

const configs: { style: StyleId; strength: number }[] = [
  { style: "balanced", strength: 0 },
  { style: "aggressive", strength: 0.5 },
  { style: "aggressive", strength: 1 },
  { style: "solid", strength: 0.5 },
  { style: "solid", strength: 1 },
];
const zero = (): Features => Object.fromEntries(FEATURE_KEYS.map((k) => [k, 0])) as Features;
const acc = configs.map(() => ({ f: zero(), kl: 0, top1: 0 }));

const t0 = performance.now();
let n = 0;
for (const p of positions.slice(0, limit)) {
  const { policy } = await backend.policy({ fen: p.fen, history: p.history?.length ? p.history : undefined, eloSelf: p.eloSelf, eloOppo: p.eloOppo });
  const feats = positionFeatures(p.fen);
  const argmax = (xs: number[]) => xs.reduce((b, x, i) => (x > xs[b] ? i : b), 0);
  configs.forEach((c, i) => {
    const d = applyStyle(policy, feats, STYLES[c.style].weights, c.strength);
    const e = expectedFeatures(d.moves, d.styled, feats);
    for (const k of FEATURE_KEYS) acc[i].f[k] += e[k];
    acc[i].kl += d.kl;
    if (argmax(d.styled) === argmax(d.base)) acc[i].top1++;
  });
  n++;
  if (n % 50 === 0) console.log(`${n}/${limit} positions`);
}
const secs = (performance.now() - t0) / 1000;

const rows = configs.map((c, i) => ({
  config: `${STYLES[c.style].name} @ ${c.strength}`,
  ...Object.fromEntries(FEATURE_KEYS.map((k) => [k, acc[i].f[k] / n])),
  meanKl: acc[i].kl / n,
  top1AgreementWithMaia: acc[i].top1 / n,
}));
mkdirSync(new URL("../eval/", import.meta.url), { recursive: true });
writeFileSync(new URL("../eval/style-eval.json", import.meta.url), JSON.stringify({ positions: n, seconds: secs, rows }, null, 2));

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const md = [
  "# Playstyle evaluation",
  "",
  `Generated by \`npm run eval:styles\` on ${n} positions (Maia-3 5M, ratings 600–2500, ${(secs / n * 1000).toFixed(0)} ms/position on the build machine).`,
  "Values are exact expectations under each style's move distribution — no sampling noise.",
  "",
  `| Config | ${FEATURE_KEYS.map((k) => FEATURE_LABELS[k]).join(" | ")} | Mean KL vs Maia (nats) | Top move = Maia's |`,
  `|---|${FEATURE_KEYS.map(() => "---:").join("|")}|---:|---:|`,
  ...rows.map((r) => `| ${r.config} | ${FEATURE_KEYS.map((k) => (k === "kingPressure" || k === "advance" ? (r as any)[k].toFixed(3) : pct((r as any)[k]))).join(" | ")} | ${r.meanKl.toFixed(3)} | ${pct(r.top1AgreementWithMaia)} |`),
  "",
  "Reading the table: rates are the probability that the chosen move has that feature (King-zone pressure and Forward moves are mean scores in [-1, 1]). ",
  "KL and top-move agreement measure the human-likeness cost: Balanced is plain Maia (KL 0, 100% agreement).",
  "",
  "Caveat: these positions come from the maia3-ts reference fixture (a few hundred positions across five rating levels), not a held-out set of real games. ",
  "The next step is to repeat this on positions from your own games and check move-match accuracy against what humans actually played.",
  "",
].join("\n");
writeFileSync(new URL("../../docs/style-eval.md", import.meta.url), md);
console.log(md);
